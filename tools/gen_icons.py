#!/usr/bin/env python3
"""Builds the icon CSS block in assets/css/main.css from the SVG files in tools/icons/.

The site no longer loads the Font Awesome library from a CDN. Icons keep the same markup,
<i class="fas fa-flask"></i> or <i class="fab fa-github"></i>, and are drawn as CSS masks with the
SVG embedded in the stylesheet (colour follows the text colour, size follows the font size).

To add an icon: copy its SVG from the Font Awesome Free 6.5.1 package (npm pack @fortawesome/fontawesome-free@6.5.1,
folder svgs/solid or svgs/brands) into tools/icons/solid/ or tools/icons/brands/, then run
    python3 tools/gen_icons.py
The checker (tools/check.py) reports any fa-xxx class used on the site that has no icon here.
Icons are Font Awesome Free by Fonticons, Inc., licence CC BY 4.0 (see tools/icons/LICENSE-FontAwesome.txt).
"""
import re, glob, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSS = os.path.join(ROOT, "assets", "css", "main.css")
ALIASES = {"search": "magnifying-glass"}   # extra class names for the same icon
START = "/* ICONS:START"
END = "/* ICONS:END */"

def enc(d):
    return d.replace("%", "%25").replace("#", "%23").replace("<", "%3C").replace(">", "%3E").replace('"', "%22")

def load():
    icons = {}
    for f in sorted(glob.glob(os.path.join(ROOT, "tools", "icons", "*", "*.svg"))):
        name = os.path.splitext(os.path.basename(f))[0]
        svg = open(f, encoding="utf-8").read()
        vb = re.search(r'viewBox="0 0 (\d+) (\d+)"', svg)
        paths = re.findall(r'<path[^>]*\sd="([^"]+)"', svg)
        if not vb or len(paths) != 1:
            sys.exit(f"{f}: expected one viewBox and exactly one path")
        w, h = int(vb.group(1)), int(vb.group(2))
        uri = "data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 {} {}'%3E%3Cpath d='{}'/%3E%3C/svg%3E".format(w, h, enc(paths[0]))
        icons[name] = (w / h, uri)
    return icons

def block(icons):
    out = [START + " generated by tools/gen_icons.py, do not edit by hand. Icons: Font Awesome Free 6.5.1 by Fonticons, Inc. (https://fontawesome.com), licence CC BY 4.0 (https://fontawesome.com/license/free) */",
           ".fas, .fab { display: inline-block; width: 1em; height: 1em; line-height: 1; vertical-align: -.125em; font-style: normal; background-color: currentColor; -webkit-mask: var(--fa) center / 100% 100% no-repeat; mask: var(--fa) center / 100% 100% no-repeat; }",
           "@media (forced-colors: active) { .fas, .fab { background-color: CanvasText; } }"]
    names = {}
    for n, (ratio, uri) in icons.items():
        names[n] = (ratio, uri)
    for alias, target in ALIASES.items():
        if target in icons: names[alias] = icons[target]
    for n in sorted(names):
        ratio, uri = names[n]
        w = "" if abs(ratio - 1) < .01 else " width: {}em;".format(round(ratio, 3))
        out.append('.fa-{} {{ --fa: url("{}");{} }}'.format(n, uri, w))
    out.append(END)
    return "\n".join(out)

def main():
    css = open(CSS, encoding="utf-8").read()
    new = block(load())
    if START in css:
        a = css.index(START); b = css.index(END) + len(END)
        css = css[:a] + new + css[b:]
    else:
        css = css.rstrip("\n") + "\n\n" + new + "\n"
    open(CSS, "w", encoding="utf-8").write(css)
    print("icons written:", len(load()), "plus aliases", list(ALIASES))

if __name__ == "__main__":
    main()
